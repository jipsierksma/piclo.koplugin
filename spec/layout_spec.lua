local Layout = require("piclogic/ui/layout")

describe("fitPicture", function()
    it("uses the largest whole-pixel scale and centers", function()
        local s, ox, oy = Layout.fitPicture(15, 15, 100, 80)
        assert.are.equal(5, s)
        assert.are.equal(12, ox)
        assert.are.equal(2, oy)
    end)

    it("returns 0 when nothing fits", function()
        assert.are.equal(0, (Layout.fitPicture(15, 15, 10, 10)))
    end)
end)

describe("tileGrid", function()
    it("fits a 12-puzzle pack on one Oasis portrait page", function()
        local g = Layout.tileGrid(12, 1162, 1400, 50, 51, 211)
        assert.are.equal(1, g.pages)
        assert.are.equal(3, g.cols)
        assert.are.equal(4, g.rows)
        assert.is_true(g.tile >= 211)
        assert.is_true(g.cols * g.tile + (g.cols - 1) * 51 <= 1162)
        assert.is_true(g.rows * (g.tile + 50) + (g.rows - 1) * 51 <= 1400)
    end)

    it("prefers wider grids in landscape", function()
        local g = Layout.tileGrid(12, 1500, 900, 50, 51, 180)
        assert.are.equal(1, g.pages)
        assert.is_true(g.cols >= 4)
    end)

    it("pages when tiles would get too small", function()
        local g = Layout.tileGrid(40, 600, 700, 30, 20, 150)
        assert.is_true(g.pages > 1)
        assert.is_true(g.tile >= 150)
        assert.are.equal(g.cols * g.rows, g.per_page)
        assert.is_true(g.rows * (g.tile + 30) + (g.rows - 1) * 20 <= 700)
    end)
end)
