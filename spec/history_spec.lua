local History = require("piclogic/model/history")

describe("history", function()
    it("starts empty", function()
        local h = History.new()
        assert.is_false(h:canUndo())
        assert.is_false(h:canRedo())
        assert.is_nil(h:undo())
        assert.is_nil(h:redo())
    end)

    it("undoes in reverse order and redoes forward", function()
        local h, a, b = History.new(), { "a" }, { "b" }
        h:push(a)
        h:push(b)
        assert.are.equal(b, h:undo())
        assert.are.equal(a, h:undo())
        assert.are.equal(a, h:redo())
        assert.are.equal(b, h:redo())
    end)

    it("drops the redo branch on a new move", function()
        local h = History.new()
        h:push({ "a" })
        h:undo()
        h:push({ "b" })
        assert.is_false(h:canRedo())
    end)

    it("forgets the oldest moves past its limit", function()
        local h = History.new(2)
        h:push({ 1 })
        h:push({ 2 })
        h:push({ 3 })
        assert.are.same({ 3 }, h:undo())
        assert.are.same({ 2 }, h:undo())
        assert.is_nil(h:undo())
    end)
end)
